import { createServer } from 'vite';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const vite = await createServer({
  root,
  appType: 'custom',
  logLevel: 'silent',
  server: { middlewareMode: true },
});

const q = (value) =>
  value === null || value === undefined || value === ''
    ? 'NULL'
    : `'${String(value).replaceAll('\\', '\\\\').replaceAll("'", "''")}'`;
const j = (value) => (value === null || value === undefined ? 'NULL' : q(JSON.stringify(value)));

function upsert(table, columns, rows, key = 'slug') {
  const keys = Array.isArray(key) ? key : [key];
  const values = rows
    .map((row) => `  (${columns.map((col) => row[col] ?? 'NULL').join(', ')})`)
    .join(',\n');
  const updates = columns
    .filter((col) => !keys.includes(col) && col !== 'id')
    .map((col) => `\`${col}\` = VALUES(\`${col}\`)`)
    .join(', ');
  return `INSERT INTO \`${table}\` (${columns.map((c) => `\`${c}\``).join(', ')}) VALUES\n${values}\nON DUPLICATE KEY UPDATE ${updates};\n`;
}

try {
  const { clients } = await vite.ssrLoadModule('/src/content/clients.js');
  const { apps } = await vite.ssrLoadModule('/src/content/apps.js');
  const { posts } = await vite.ssrLoadModule('/src/content/posts.js');
  const { experiences, skillGroups } = await vite.ssrLoadModule('/src/content/experience.js');
  const { profile } = await vite.ssrLoadModule('/src/content/profile.js');

  const clientRows = clients.map((client, index) => ({
    slug: q(client.slug),
    name: q(client.name),
    kicker: q(client.kicker),
    type: q(client.type),
    role: q(client.role),
    period: q(client.dates),
    location: q(client.location),
    website: q(client.website),
    logo: q(client.logo),
    metric: q(client.metric),
    metric_label: q(client.metricLabel),
    summary: q(client.summary),
    challenge: q(client.challenge),
    what_i_did: j(client.did),
    outcome: q(client.outcome),
    stack: j(client.stack),
    facts: j(client.facts),
    store_url: q(client.links?.store),
    published: '1',
    sort_order: String(index),
  }));

  const appRows = apps.map((app, index) => ({
    slug: q(app.slug),
    name: q(app.name),
    tagline: q(app.tagline),
    role: q(app.role),
    year: q(app.year),
    platforms: j(app.platforms),
    genre: q(app.genre),
    icon: q(app.icon),
    screenshots: j(app.screenshots),
    rating_value: app.rating ? String(app.rating.value) : 'NULL',
    rating_count: app.rating ? String(app.rating.count) : 'NULL',
    stack: j(app.stack),
    links: j(app.links),
    summary: q(app.summary),
    features: j(app.features),
    story: q(app.story),
    metrics: j(app.metrics),
    published: '1',
    sort_order: String(index),
  }));

  const postRows = posts.map((post) => ({
    slug: q(post.slug),
    title: q(post.title),
    dek: q(post.dek),
    post_date: q(post.date),
    category: q(post.category),
    tags: j(post.tags),
    minutes: String(post.minutes),
    body: q(post.body),
    published: '1',
  }));

  const experienceRows = experiences.map((role, index) => ({
    company: q(role.company),
    position: q(role.role),
    period: q(role.period),
    location: q(role.location),
    summary: q(role.summary),
    points: j(role.points),
    sort_order: String(index),
  }));

  let skillIndex = 0;
  const skillRows = skillGroups.flatMap((group) =>
    group.items.map((name) => ({
      grp: q(group.label),
      name: q(name),
      sort_order: String(skillIndex++),
    })),
  );

  const profileRows = Object.entries(profile).map(([key, value]) => ({
    k: q(key),
    v: q(value),
  }));

  const sql = `-- Generated by \`npm run seed:sql\` — imports the site's content into the CMS.
-- Safe to re-import: rows are upserted by their natural keys, ids are preserved.
-- Requires api/schema.sql and api/v2-schema.sql to be applied first.

${upsert('clients', ['slug','name','kicker','type','role','period','location','website','logo','metric','metric_label','summary','challenge','what_i_did','outcome','stack','facts','store_url','published','sort_order'], clientRows)}

${upsert('apps', ['slug','name','tagline','role','year','platforms','genre','icon','screenshots','rating_value','rating_count','stack','links','summary','features','story','metrics','published','sort_order'], appRows)}

${upsert('posts', ['slug','title','dek','post_date','category','tags','minutes','body','published'], postRows)}

${upsert('experiences', ['company','position','period','location','summary','points','sort_order'], experienceRows, ['company','position'])}

${upsert('skills', ['grp','name','sort_order'], skillRows, ['grp','name'])}

${upsert('profile', ['k','v'], profileRows, 'k')}
`;

  await writeFile(path.join(root, 'api', 'seed-content.sql'), sql);
  console.log(
    `api/seed-content.sql — ${clients.length} clients, ${apps.length} apps, ${posts.length} posts, ` +
      `${experienceRows.length} roles, ${skillRows.length} skills, ${profileRows.length} profile fields`,
  );
} finally {
  await vite.close();
}
